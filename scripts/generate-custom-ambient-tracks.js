#!/usr/bin/env node
/* Deterministically enumerate .mp3 files and emit a TS module consumed by the app.
 * Do not guess directories: scan these, in order, if they exist:
 *   - public/audio
 *   - public/sfx
 *   - src/assets/audio
 * Output: src/audio/customAmbientTracks.generated.ts
 */

const fs = require('fs');
const path = require('path');

const ROOT = process.cwd();
const CANDIDATE_DIRS = [
  'public/audio',
  'public/sfx',
  'src/assets/audio'
];

const OUT_FILE = path.join(ROOT, 'src/audio/customAmbientTracks.generated.ts');

function listMp3s(dir) {
  if (!fs.existsSync(dir)) return [];
  const walk = (p) => {
    const entries = fs.readdirSync(p, { withFileTypes: true });
    let acc = [];
    for (const e of entries) {
      const full = path.join(p, e.name);
      if (e.isDirectory()) acc = acc.concat(walk(full));
      else if (e.isFile() && e.name.toLowerCase().endsWith('.mp3')) acc.push(full);
    }
    return acc;
  };
  return walk(dir);
}

const files = [];
for (const d of CANDIDATE_DIRS) {
  const abs = path.join(ROOT, d);
  files.push(...listMp3s(abs));
}

// Convert absolute to web-servable URLs:
// - If under public/, strip the leading "public" so URL is "/audio/..."
// - If under src/assets/*, emit a relative import path for bundlers (keep it as project-relative)
function toTrackDescriptor(absPath) {
  const rel = path.relative(ROOT, absPath).replace(/\\/g, '/');
  const lower = rel.toLowerCase();

  let url;
  if (lower.startsWith('public/')) {
    url = '/' + rel.slice('public/'.length);
  } else {
    // Keep as relative for bundlers (Vite/Rollup will handle asset URLing)
    url = '/' + rel; // standardize with leading slash
  }

  // Stable ID: use path sans extension, kebab-cased
  const base = path.basename(rel, path.extname(rel));
  const dir = path.dirname(rel).replace(/\//g, '_');
  const id = [dir, base].filter(Boolean).join('_').replace(/[^a-zA-Z0-9_-]/g, '-');

  // Mode tags: conservative defaults; do not guess aggressively.
  // If file path hints (e.g., "night", "dawn", "dusk", "market", "forest", "coast"), add those tags.
  const tags = [];
  const tagFrom = rel.toLowerCase();
  if (/(night|midnight)/.test(tagFrom)) tags.push('night');
  if (/(dawn)/.test(tagFrom)) tags.push('dawn');
  if (/(dusk|sunset|golden)/.test(tagFrom)) tags.push('dusk', 'golden_hour');
  if (/(day|noon|high_noon)/.test(tagFrom)) tags.push('day', 'high_noon');
  if (/(market|agora)/.test(tagFrom)) tags.push('market');
  if (/(forest)/.test(tagFrom)) tags.push('forest');
  if (/(coast|port|harbor|harbour|sea|ocean|shore)/.test(tagFrom)) tags.push('coast');

  // Always include a generic tag so it’s selectable: 'ambient'
  if (!tags.length) tags.push('ambient');

  return { id, url, tags: Array.from(new Set(tags)) };
}

const tracks = Array.from(new Map(
  files.map(f => {
    const d = toTrackDescriptor(f);
    return [d.id, d];
  })
).values());

const header = `// AUTO-GENERATED FILE. DO NOT EDIT.
// Generated by scripts/generate-custom-ambient-tracks.js
// Contains discovered .mp3 assets as ambient tracks.

export type CustomAmbientTrack = {
  id: string;
  url: string;
  tags: string[];
};

export const CUSTOM_AMBIENT_TRACKS: CustomAmbientTrack[] = ${JSON.stringify(tracks, null, 2)};
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, header, 'utf8');

console.log(`[ambient] wrote ${OUT_FILE} with ${tracks.length} track(s)`);
