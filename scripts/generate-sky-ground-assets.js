#!/usr/bin/env node
/* Generate a manifest of sky/ground JPGs.
 * Scan these folders if they exist, recursively:
 *   public/textures/sky, public/textures/ground,
 *   public/sky, public/ground,
 *   src/assets/sky, src/assets/ground
 * Output: src/assets/skyGround.generated.ts
 */
const fs = require('fs');
const path = require('path');

const ROOT = process.cwd();
const CANDIDATES = [
  'public/textures/sky',
  'public/textures/ground',
  'public/sky',
  'public/ground',
  'src/assets/sky',
  'src/assets/ground'
];

const OUT_FILE = path.join(ROOT, 'src/assets/skyGround.generated.ts');

function list(dir) {
  if (!fs.existsSync(dir)) return [];
  const out = [];
  const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const full = path.join(d, e.name);
      if (e.isDirectory()) walk(full);
      else if (e.isFile() && /\.(jpe?g)$/i.test(e.name)) out.push(full);
    }
  };
  walk(dir);
  return out;
}

function toUrl(abs) {
  const rel = path.relative(ROOT, abs).replace(/\\/g, '/');
  if (rel.startsWith('public/')) {
    return '/' + rel.slice('public/'.length); // served as absolute
  }
  return '/' + rel; // bundler will rewrite; leading slash standardizes
}

function classify(rel) {
  const lower = rel.toLowerCase();
  if (/(sky|cloud|sunset|dawn|dusk|noon|night|midnight)/.test(lower)) return 'sky';
  if (/(ground|grass|dirt|rock|sand|soil)/.test(lower)) return 'ground';
  // default by folder name
  if (/\/sky\//.test(lower)) return 'sky';
  if (/\/ground\//.test(lower)) return 'ground';
  return 'ground'; // conservative default
}

function tagsFor(rel, kind) {
  const t = rel.toLowerCase();
  const tags = new Set([kind]);
  if (/night|midnight/.test(t)) tags.add('night');
  if (/dawn/.test(t)) tags.add('dawn');
  if (/dusk|sunset|golden/.test(t)) tags.add('dusk') || tags.add('golden_hour');
  if (/noon|day|high_noon/.test(t)) tags.add('day') || tags.add('high_noon');
  if (/coast|port|harbor|harbour|sea|ocean|shore/.test(t)) tags.add('coast');
  if (/forest/.test(t)) tags.add('forest');
  return Array.from(tags);
}

const files = CANDIDATES.flatMap((d) => list(path.join(ROOT, d)));
const unique = Array.from(new Set(files));
const entries = unique.map((abs) => {
  const rel = path.relative(ROOT, abs).replace(/\\/g, '/');
  const url = toUrl(abs);
  const kind = classify(rel);
  const id = rel.replace(/\.[^.]+$/, '').replace(/[^a-zA-Z0-9\/_-]/g, '-').replace(/\//g, '_');
  return { id, url, kind, tags: tagsFor(rel, kind) };
});

const header = `// AUTO-GENERATED. DO NOT EDIT.
// Generated by scripts/generate-sky-ground-assets.js

export type SkyGroundAsset = {
  id: string;
  url: string;
  kind: 'sky' | 'ground';
  tags: string[];
};

export const SKY_JPGS: SkyGroundAsset[] = ${JSON.stringify(
  entries.filter((e) => e.kind === 'sky'),
  null,
  2
)};

export const GROUND_JPGS: SkyGroundAsset[] = ${JSON.stringify(
  entries.filter((e) => e.kind === 'ground'),
  null,
  2
)};
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, header, 'utf8');
console.log(`[sky/ground] wrote ${OUT_FILE} with ${entries.length} asset(s)`);
